"""Writes docs/BALANCE.md from data/enemies.json, data/gear.json and data/difficulties.json,
so the numbers in the doc can never drift from the game. Run from the game folder."""
import json
import math
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
enemies = {e["id"]: e for e in json.loads((root / "data/enemies.json").read_text())}
gear = json.loads((root / "data/gear.json").read_text())
levels = json.loads((root / "data/difficulties.json").read_text())
SWING = 0.07 + 0.12 + 0.20
PLAYER_LEVEL_DAMAGE = 1


def weapons():
    items = gear if isinstance(gear, list) else list(gear.values())
    return [g for g in items if g.get("slot") == "weapon"]


def hits(damage, hp):
    return math.ceil(hp / damage)


lines = [
    "# Balance table",
    "",
    "Generated by `tools/balance_doc.py` from `data/enemies.json`, `data/gear.json` and",
    "`data/difficulties.json`. A swing takes 0.39s (windup 0.07, active 0.12, recovery 0.20)",
    "and costs 14 stamina. Level gives +1 damage per level above 1 and +8 max health per level.",
    "All numbers below are Medium; other difficulties multiply them.",
    "",
    "## Hits to defeat an enemy (Medium)",
    "",
    "| Weapon | Damage | " + " | ".join(f"{e['name']} ({e['hp']} hp)" for e in enemies.values()) + " |",
    "|---|---|" + "---|" * len(enemies),
]
for weapon in weapons():
    damage = weapon.get("damage", 3)
    cells = [f"{hits(damage, e['hp'])} hits ({hits(damage, e['hp']) * SWING:.1f}s)" for e in enemies.values()]
    lines.append(f"| {weapon['name']} | {damage} | " + " | ".join(cells) + " |")
lines += [
    "",
    "## Enemies",
    "",
    "| Enemy | HP | Damage | Windup | Cooldown | Speed | XP |",
    "|---|---|---|---|---|---|---|",
]
for e in enemies.values():
    lines.append(f"| {e['name']} | {e['hp']} | {e['damage']} | {e['windup']}s | {e['cooldown']}s | {e['speed']} | {e['xp']} |")
lines += [
    "",
    "Armor lets `40/(40+DEF)` of a strike through; a block cuts that by 80% and costs stamina",
    "equal to 90% of the raw damage; a parry takes none, refunds 18 stamina and stuns the enemy.",
    "",
    "## Stamina and the guard",
    "",
    "- 100 stamina plus 4 per level; regenerates 34/s after a 0.55s pause (times the difficulty).",
    "- Swing: 14. Raising the guard: 6, then 10/s while held.",
    "- The guard drops after 1.6s, then 1.2s cooldown. If stamina empties, or a blow is too heavy, the guard breaks: 2.2s cooldown.",
    "",
    "## Difficulties",
    "",
    "| Level | Zombie HP | Damage | Speed | Windup | Packs | Lives | Mistakes | XP | Thirst | Parry window |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]
for d in levels:
    lines.append(
        f"| {d['name']} | x{d['enemy_hp']} | x{d['enemy_damage']} | x{d['enemy_speed']} | x{d['enemy_windup']} | "
        f"x{d['spawn']} | {d['lives']} | x{d['penalty']} | x{d['xp']} | x{d['water_decay']} | {d['parry_window']}s |"
    )
(root / "docs/BALANCE.md").write_text("\n".join(lines) + "\n")
print("docs/BALANCE.md written")
